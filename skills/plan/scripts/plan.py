#!/usr/bin/env python3
"""Deterministic bookkeeping for plans under plans/ at the repository root.

A plan is a folder plans/<NNNN>-<slug>/ holding plan.md and the plan's helper files; plan.md has a markdown table whose header has the columns `#`, `Step` and `Status`
(optionally `Done when`). plans/CURRENT_PLAN holds the slug of the active plan (the Claude statusline shows it).
A flat plans/<NNNN>-<slug>.md from before the folder layout is still read and updated.

`new` writes the plan folder in the record format (folder.py; hal2's decision record `record-formats`): plan.md with
a front matter envelope, the ledgers decisions.md and questions.md and the committed handoff.md. A plan.md without
front matter is legacy: its `Landing:`, `Grilled:`, `Finished:` and `Autogenerated:` values are lines below the title
(a record's: the front matter keys `landing`, `grilled`, `finished`, `autogenerated`; the JSON is the same for both,
`format` says which).

  plan.py new "<title>" [--goal "<goal>"] [--research] [--no-current] [--fetch]
                                                           create the next plan from the template; its number
                                                           is unique across all worktrees and branches
                                                           (plan_number.py; --fetch sees other clones too);
                                                           --research: a research plan, slug <NNNN>-research-<topic>;
                                                           writes `landing: auto` (--manual-landing, and every
                                                           research plan: manual);
                                                           --autogenerated <by>: `autogenerated: <by>, <date>`
                                                           (a plan a watcher made; hal2 marks it)
  plan.py current                                          print the current plan as JSON
  plan.py list                                             print every plan as JSON
  plan.py use <slug-or-number>                             make a plan current
  plan.py status <step> "<status>" [--plan <slug>]         set one step's Status cell; `next` also writes the
                                                           step's file steps/<step>.md from templates/step.md
                                                           when it is missing (never overwrites; not for a
                                                           parallel plan, whose brief is `brief`), named in the
                                                           JSON's `step_file`
  plan.py grilled [--auto] [--plan <slug>]                 set the plan's `Grilled:` line to today; --auto counts
                                                           one autogrill round: `Grilled: <date> (autogrill ×n)`,
                                                           a grill by the user adds `, grill`
  plan.py landing auto|manual [--plan <slug>]              set the plan's `Landing:` line: auto lands the plan
                                                           with /mtm when its last step is done, manual waits
                                                           for the user's /mtm (a plan without the line)
  plan.py uat [--plan <slug>] [--shotfile <name>]          scaffold the plan's uat.md (checks the user runs on the
                                                           default branch after the landing) from the template;
                                                           the shotfile defaults to the title's first word
  plan.py check [<plan folder>...]                         the plan-folder check: exit 1 when a plan number is
                                                           used twice or hal2's records checker (`hal2-cli-records
                                                           check --json`, checker.py: $HAL2_CLI_RECORDS, else on
                                                           PATH) finds a problem in a plan folder's records
                                                           (plan.md, decisions.md, questions.md, handoff.md); one
                                                           problem per line; legacy plans pass; named folders: only
                                                           those (an example folder laid out like a repository:
                                                           `--folder` of the tree holding its plans/); without the
                                                           checker one line `records unchecked: ...`, exit 0
  plan.py scaffold [--plan <slug>]                         write the ledgers and the handoff a plan in the record
                                                           format lacks (never overwrites one)
  plan.py -g ...                                           the same on the global plans folder (hal2's
                                                           plans.toml root, default ~/Documents/hal2/plans;
                                                           --global-root <dir> overrides): new (through
                                                           `hal2-cli-plans new --global`), list, status,
                                                           grilled with --plan <n>; no CURRENT_PLAN there

A parallel plan (`new --parallel`; its step table has the columns `| # | Step | Needs | Touches | Who | Done when |
Status |`, parallel.py) adds `parallel`, `running` and `ready` to the JSON, and these commands (skills plan 0013):
  plan.py ready [--limit <n>] [--json]                     the steps that can start now: open, every Need done,
                                                           their Touches free (greedy in table order); --json adds
                                                           why each other open step waits
  plan.py assign <step> <who> [--force]                    who: lead, subagent, user or slot NN (30-99); sets Who
                                                           and `running` (a step not ready only with --force); a
                                                           slot NN that exists gets its plans/LEAD marker; a slot
                                                           another step holds, whose marker names other work or
                                                           that runs a farmer servant only with --force
  plan.py brief <step>                                     scaffold steps/<step>.md (templates/step-brief.md) and
                                                           print the subservant's exact first prompt
  plan.py report <step>                                    scaffold reports/<step>.md (templates/report.md)
  plan.py reports [--no-fetch]                             the running subservants' reports arrived on origin/NN
  plan.py watch [--interval 60] [--rounds n]               one line per newly arrived report (the lead's Monitor)
A cell holds a literal `|` written `\\|`. In a subservant's slot (plans/LEAD: `<lead-slot> <plan> <step>`, `lead` in
the JSON) new, status, assign, grilled, landing, uat and brief are refused: plan.md is the lead's (also with
--root <lead's checkout> when the current directory is in a marked slot).

Run from anywhere inside the repo, or pass --root. Prints JSON on stdout; exits 1 with a message on stderr.

The JSON's `landing` is the plan's `Landing:` line (auto|manual; none for a global plan), each step's
`after_landing` says its done-when starts with "after the landing" (or the older "after the user's `/mtm`"), `next`
is the first open step to run before the landing (an after-landing step only when no other is open), `land` is
`ready` when no open step must run before the landing (`wait` otherwise; `manual`, `none` from `landing`), and
`problems` lists after-landing steps followed by steps that are not. `current` and `status` add `switch`: the
`next` step's model and effort when they differ from the running Claude Code session's (session.py), else null.
"""
