PLANS = Path("plans")
POINTER = "CURRENT_PLAN"
PLAN_RE = re.compile(r"^(\d{4})-[a-z0-9-]+$")
MAIN = "plan.md"
TEMPLATE = Path(__file__).resolve().parent.parent / "templates" / "plan.md"
UAT_TEMPLATE = TEMPLATE.parent / "uat.md"
